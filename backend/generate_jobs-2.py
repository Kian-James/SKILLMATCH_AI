"""
generate_jobs.py
────────────────
Seeds Firestore with jobs derived directly from labels.json.

For each entry in labels.json:
  - title           ← expected_job_title
  - required_skills ← expected_skills
  - industry        ← inferred from filename prefix (Com → Computing, Eng → Engineering)
  - description     ← generated by Llama 3.1 8B (the ONLY thing the LLM writes)
  - embedding       ← SBERT all-MiniLM-L6-v2

Duplicate titles are skipped — one Firestore doc per unique job title.

Usage:
    python generate_jobs.py

Requirements in .env:
    HF_TOKEN                   – Hugging Face API token
    FIREBASE_CREDENTIALS_PATH  – path to your serviceAccountKey.json
    FIRESTORE_JOBS_COLLECTION  – Firestore collection name (default: jobs)
    LABELS_PATH                – path to labels.json (default: ./labels.json)
    BATCH_SIZE                 – description requests per API call (default: 5)
    MAX_RETRIES                – retries per failed API call (default: 3)
"""

import os
import sys
import json
import re
import time
import requests
import torch
from dotenv import load_dotenv
from sentence_transformers import SentenceTransformer

# ── Load .env ────────────────────────────────────────────────────────────────
load_dotenv()

HF_TOKEN                  = os.getenv("HF_TOKEN")
FIREBASE_CREDENTIALS_PATH = os.getenv("FIREBASE_CREDENTIALS_PATH")
FIRESTORE_JOBS_COLLECTION = os.getenv("FIRESTORE_JOBS_COLLECTION", "jobs")
LABELS_PATH               = os.getenv("LABELS_PATH", "./labels.json")
BATCH_SIZE                = int(os.getenv("BATCH_SIZE", "5"))
MAX_RETRIES               = int(os.getenv("MAX_RETRIES", "3"))

HF_API_URL = "https://router.huggingface.co/v1/chat/completions"
HF_MODEL   = "meta-llama/Llama-3.1-8B-Instruct:cerebras"

# ── Validate env ─────────────────────────────────────────────────────────────
errors = []
if not HF_TOKEN:
    errors.append("HF_TOKEN is not set.")
if not FIREBASE_CREDENTIALS_PATH:
    errors.append("FIREBASE_CREDENTIALS_PATH is not set.")
elif not os.path.exists(FIREBASE_CREDENTIALS_PATH):
    errors.append(f"Credentials file not found: {FIREBASE_CREDENTIALS_PATH}")
if not os.path.exists(LABELS_PATH):
    errors.append(f"labels.json not found at: {LABELS_PATH}")

if errors:
    for e in errors:
        print(f"[ERROR] {e}")
    sys.exit(1)

# ── SBERT ─────────────────────────────────────────────────────────────────────
print("[INFO] Loading SBERT (sentence-transformers/all-MiniLM-L6-v2) …")
device = "cuda" if torch.cuda.is_available() else "cpu"
sbert  = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2", device=device)
print(f"[INFO] SBERT ready on {device.upper()}.\n")

# ── Firebase ──────────────────────────────────────────────────────────────────
import firebase_admin
from firebase_admin import credentials, firestore

if not firebase_admin._apps:
    cred = credentials.Certificate(FIREBASE_CREDENTIALS_PATH)
    firebase_admin.initialize_app(cred)

db = firestore.client()


# ── Load + deduplicate labels ─────────────────────────────────────────────────

def infer_industry(filename: str) -> str:
    """Com - *.pdf → Computing, Eng - *.pdf → Engineering."""
    return "Engineering" if filename.startswith("Eng") else "Computing"


def title_to_doc_id(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")


def load_unique_jobs(labels_path: str) -> list:
    """
    Read labels.json and return one job per unique expected_job_title.
    Skips entries with empty titles or empty skill lists.
    required_skills are deduplicated and capped at 8.
    """
    with open(labels_path, "r", encoding="utf-8") as f:
        labels: dict = json.load(f)

    seen_titles: dict = {}   # title → job dict (first occurrence wins)

    for filename, entry in labels.items():
        raw_title  = entry.get("expected_job_title", "").strip()
        raw_skills = entry.get("expected_skills", [])

        if not raw_title or not raw_skills:
            continue

        # Normalise title for dedup key
        key = raw_title.lower().strip()
        if key in seen_titles:
            continue

        # Clean skills: strip whitespace, drop empties, deduplicate (preserve order)
        seen_skills = set()
        clean_skills = []
        for s in raw_skills:
            s = str(s).strip()
            if s and s.lower() not in seen_skills:
                seen_skills.add(s.lower())
                clean_skills.append(s)

        if not clean_skills:
            continue

        seen_titles[key] = {
            "title":           raw_title,
            "required_skills": clean_skills[:8],   # cap at 8 — LLM handles extras
            "industry":        infer_industry(filename),
        }

    jobs = list(seen_titles.values())
    print(f"[INFO] {len(jobs)} unique job titles loaded from labels.json.")
    return jobs


# ── LLM: generate descriptions ────────────────────────────────────────────────

SYSTEM_PROMPT = """You are a job description writer. Given a job title, industry, and required skills, write a short professional job description.

Output ONLY a valid JSON array — no markdown, no code fences, no explanation.

Each element must match this exact schema:
{"title": "...", "description": "..."}

Rules:
- "description" must be exactly 2 sentences
- Mention specific skills from the required_skills list naturally
- No special characters, no newlines inside strings
- Output ONLY the raw JSON array"""


def build_description_prompt(batch: list) -> str:
    """Ask the LLM to write descriptions for a batch of jobs."""
    items = []
    for job in batch:
        items.append(
            f'- Title: "{job["title"]}" | Industry: {job["industry"]} '
            f'| Skills: {", ".join(job["required_skills"])}'
        )
    jobs_block = "\n".join(items)
    return (
        f"Write a 2-sentence job description for each of these {len(batch)} roles.\n\n"
        f"{jobs_block}\n\n"
        f"Return ONLY a JSON array with exactly {len(batch)} objects "
        f'using the schema {{"title": "...", "description": "..."}}.'
    )


def call_llama(prompt: str) -> str:
    headers = {
        "Authorization": f"Bearer {HF_TOKEN}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": HF_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user",   "content": prompt},
        ],
        "max_tokens": 2048,
        "temperature": 0.5,
        "stream": False,
    }
    response = requests.post(HF_API_URL, headers=headers, json=payload, timeout=120)
    if response.status_code != 200:
        raise RuntimeError(f"API {response.status_code}: {response.text[:300]}")
    return response.json()["choices"][0]["message"]["content"].strip()


def _repair_truncated_json(raw: str) -> list:
    """Brace-depth scanner — salvages complete objects from truncated output."""
    objects, depth, start = [], 0, None
    for i, ch in enumerate(raw):
        if ch == "{":
            if depth == 0:
                start = i
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and start is not None:
                try:
                    objects.append(json.loads(raw[start:i + 1]))
                except json.JSONDecodeError:
                    pass
                start = None
    return objects


def parse_descriptions(raw: str) -> dict:
    """Return {title_lower: description} from the LLM response."""
    cleaned = re.sub(r"```(?:json)?", "", raw).strip().strip("`").strip()
    start, end = cleaned.find("["), cleaned.rfind("]") + 1

    if start != -1 and end > start:
        try:
            items = json.loads(cleaned[start:end])
        except json.JSONDecodeError:
            items = _repair_truncated_json(cleaned)
    else:
        items = _repair_truncated_json(cleaned)

    result = {}
    for item in items:
        t = item.get("title", "").strip()
        d = item.get("description", "").strip().replace("\n", " ")
        if t and d:
            result[t.lower()] = d
    return result


def generate_descriptions(jobs: list) -> list:
    """
    Split jobs into batches, call LLM for descriptions, attach to jobs.
    Falls back to a templated description if the LLM misses a title.
    """
    total   = len(jobs)
    batches = [jobs[i:i + BATCH_SIZE] for i in range(0, total, BATCH_SIZE)]
    desc_map = {}

    for idx, batch in enumerate(batches, 1):
        print(f"  [LLM {idx}/{len(batches)}] Generating descriptions for {len(batch)} job(s) …")

        for attempt in range(1, MAX_RETRIES + 1):
            try:
                raw     = call_llama(build_description_prompt(batch))
                parsed  = parse_descriptions(raw)
                desc_map.update(parsed)
                break
            except (RuntimeError, ValueError) as exc:
                print(f"    [RETRY {attempt}/{MAX_RETRIES}] {exc}")
                if attempt < MAX_RETRIES:
                    time.sleep(2 ** attempt)
                else:
                    print(f"    [WARN] Batch {idx} failed — using fallback descriptions.")

        time.sleep(1)

    # Attach descriptions back onto job dicts
    for job in jobs:
        key = job["title"].lower()
        if key in desc_map:
            job["description"] = desc_map[key]
        else:
            # Fallback: template-generated description
            job["description"] = (
                f"This role requires expertise in {', '.join(job['required_skills'][:3])}. "
                f"The {job['title']} will work within the {job['industry']} domain "
                f"delivering high-quality solutions."
            )
            print(f"  [FALLBACK] '{job['title']}' — used template description.")

    return jobs


# ── Embedding ─────────────────────────────────────────────────────────────────

def embed_jobs(jobs: list) -> list:
    profiles = [
        f"Job: {j['title']}. Industry: {j['industry']}. "
        f"Core Skills: {' '.join(j['required_skills'] * 3)}. "
        f"Desc: {j['description']}"
        for j in jobs
    ]
    print(f"\n[EMBED] Encoding {len(jobs)} job(s) with SBERT …")
    vecs = sbert.encode(profiles, convert_to_numpy=True, show_progress_bar=True)
    for job, vec in zip(jobs, vecs):
        job["embedding"] = vec.astype(float).tolist()
    return jobs


# ── Seeder ────────────────────────────────────────────────────────────────────

def seed_jobs(jobs: list) -> None:
    collection_ref = db.collection(FIRESTORE_JOBS_COLLECTION)
    print(f"\n[INFO] Seeding {len(jobs)} jobs into '{FIRESTORE_JOBS_COLLECTION}' …")

    computing   = 0
    engineering = 0

    for job in jobs:
        doc_id = title_to_doc_id(job["title"])
        collection_ref.document(doc_id).set(job)
        tag = "COM" if job["industry"] == "Computing" else "ENG"
        print(f"  ✓  [{tag}] {job['title']}  ({len(job['required_skills'])} skills)")
        if job["industry"] == "Computing":
            computing += 1
        else:
            engineering += 1

    print(f"\n[SUCCESS] {len(jobs)} job documents written to Firestore.")
    print(f"[INFO]    Computing jobs   : {computing}")
    print(f"[INFO]    Engineering jobs : {engineering}")
    print(f"[INFO]    Each document includes a 384-dim SBERT embedding.")
    print(f"[INFO]    Collection : {FIRESTORE_JOBS_COLLECTION}")
    print(f"[INFO]    Model used : {HF_MODEL} (descriptions only)")


# ── Main ──────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    # 1. Load all unique jobs from labels.json (title + skills + industry)
    jobs = load_unique_jobs(LABELS_PATH)

    if not jobs:
        print("[ERROR] No valid jobs found in labels.json.")
        sys.exit(1)

    # 2. LLM writes the description for each job
    print(f"\n[INFO] Generating descriptions via {HF_MODEL} …")
    jobs = generate_descriptions(jobs)

    # 3. SBERT encodes each job into a 384-dim embedding
    jobs = embed_jobs(jobs)

    # 4. Write everything to Firestore
    # Final document shape:
    # {
    #   "title":           "Lead Developer",          ← from expected_job_title
    #   "required_skills": ["AWS", "Docker", ...],    ← from expected_skills
    #   "industry":        "Computing",               ← inferred from filename
    #   "description":     "...",                     ← written by LLM
    #   "embedding":       [0.12, -0.34, ...],        ← SBERT vector
    # }
    seed_jobs(jobs)
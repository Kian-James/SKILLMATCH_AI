import 'dart:convert';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:http/http.dart' as http;
import '../firebase_options.dart'; // Generated by FlutterFire CLI

/// Initialize Firebase and provide Firestore/Auth access.
/// Calls to Cloud Functions are done via HTTPS using http package.
class FirebaseConfig {
  static FirebaseApp? _app;

  /// Initialize Firebase
  static Future<FirebaseApp> initFirebase() async {
    if (_app != null) return _app!;

    WidgetsFlutterBinding.ensureInitialized();
    _app = await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );

    return _app!;
  }

  /// Firestore instance
  static FirebaseFirestore get firestore => FirebaseFirestore.instance;

  /// Firebase Auth instance
  static FirebaseAuth get auth => FirebaseAuth.instance;

  /// Call a Firebase HTTPS Callable Function via HTTP POST
  ///
  /// [functionUrl] → Full HTTPS URL of your deployed Cloud Function
  /// [data] → Map of data to send to the function
  ///
  /// Example functionUrl:
  /// https://us-central1-your-project.cloudfunctions.net/processResume
  static Future<dynamic> callFunction(
      String functionUrl, Map<String, dynamic> data) async {
    try {
      final response = await http.post(
        Uri.parse(functionUrl),
        headers: {'Content-Type': 'application/json'},
        body: jsonEncode(data),
      );

      if (response.statusCode == 200) {
        return jsonDecode(response.body);
      } else {
        throw Exception(
            'Function call failed: ${response.statusCode} ${response.body}');
      }
    } catch (e) {
      throw Exception('Error calling function: $e');
    }
  }
}

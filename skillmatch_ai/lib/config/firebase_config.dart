import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_functions/firebase_functions.dart';
import '../firebase_options.dart'; // Generated by FlutterFire CLI

/// Initialize Firebase
class FirebaseConfig {
  static FirebaseApp? _app;

  static Future<FirebaseApp> initFirebase() async {
    if (_app != null) return _app!;

    WidgetsFlutterBinding.ensureInitialized();
    _app = await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );

    return _app!;
  }

  // Access Firestore
  static FirebaseFirestore get firestore => FirebaseFirestore.instance;

  // Access Firebase Auth
  static FirebaseAuth get auth => FirebaseAuth.instance;

  // Access Cloud Functions
  static FirebaseFunctions get functions => FirebaseFunctions.instance;

  /// Call a callable cloud function by name with data
  static Future<dynamic> callFunction(
      String functionName, Map<String, dynamic> data) async {
    final callable = functions.httpsCallable(functionName);
    final result = await callable.call(data);
    return result.data;
  }
}
